"""Authoritative, deterministic choices for Character Creation (not gameplay body/armor)."""
from __future__ import annotations

import json
from character_core.assemblies import lua_table
from character_core.part_names import parse_part, hair_color_channels

SLOTS = ('hair', 'head', 'eye_l', 'eye_r', 'eyebrow_l', 'eyebrow_r')


def catalog(assemblies, rows):
    if assemblies is None:
        return None
    output = {'schemaVersion': 1, 'archetypes': {}}
    for character in rows:
        assembly = character.get('assembly') or {}
        if character.get('status') != 'ASSEMBLY_READY' or not assembly.get('ready'):
            continue
        gender = character.get('gender')
        if gender not in ('male', 'female') or character.get('race') != 'human':
            continue
        rig_id = assembly['rig']['id']
        entries = {'hair': [], 'head': [], 'eyes': [], 'eyebrows': []}
        pairs = {'eye': {}, 'eyebrow': {}}
        for part in assemblies.components.snapshot()['items']:
            if part['role'] != 'part' or part['slot'] not in SLOTS or part['status'] != 'published':
                continue
            if gender not in part['allowedGenders']:
                continue
            record, error = assemblies._part(part['slot'], part['id'], rig_id, gender)
            if error or record is None:
                continue
            slot = part['slot']
            if slot in ('hair', 'head'):
                if slot == 'head' and part['id'] != (assembly['parts'].get('head') or {}).get('id'):
                    # Alternate heads need an independent atlas/appearance contract.
                    continue
                if slot == 'hair':
                    try:
                        channels = hair_color_channels({'name': part['id'], 'extras':
                            [{'name': x} for x in record['extras']]})
                    except ValueError:
                        continue
                    if record.get('attachment_mode') != 'pivot':
                        # Current color channels only support authored rigid hairstyles.
                        continue
                    record['colorChannels'] = channels
                entries[slot].append({'id': part['id'], 'part': record})
            else:
                kind, side = slot.rsplit('_', 1)
                match = parse_part(part['id'])
                key = part['id'][:-(len(side) + 1)]
                pairs[kind].setdefault(key, {})[side] = record
        for kind, target in (('eye', 'eyes'), ('eyebrow', 'eyebrows')):
            for key, sides in sorted(pairs[kind].items()):
                if set(sides) == {'l', 'r'}:
                    entries[target].append({'id': key, 'left': sides['l'], 'right': sides['r']})
        for key in entries:
            entries[key].sort(key=lambda value: value['id'])
        output['archetypes'][character['id']] = entries
    return output


def write_catalog(root, assemblies, rows):
    data = catalog(assemblies, rows)
    if data is None:
        return
    destination = root / 'assets/manifests/character-creation-appearance.json'
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    runtime = root / 'src/shared/character/CharacterCreationAppearanceRegistry.luau'
    runtime.write_text('-- generated by creation_appearance_export.py; do not edit\nreturn table.freeze(' +
                       lua_table(data) + ')\n', encoding='utf-8')
