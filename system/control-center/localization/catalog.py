"""M455: game-only translation contract; one authored manifest, deterministic Luau export.

Author edits live in assets/manifests/game-localization.json. This module contains no UI code.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

LOCALES = ('ru-ru', 'en-us', 'de-de', 'zh-cn', 'it-it', 'es-es',
           'fr-fr', 'pt-br', 'ja-jp', 'ko-kr')
NAMES = {
    'ru-ru': 'Русский', 'en-us': 'English', 'de-de': 'Deutsch',
    'zh-cn': '简体中文', 'it-it': 'Italiano', 'es-es': 'Español',
    'fr-fr': 'Français', 'pt-br': 'Português (Brasil)',
    'ja-jp': '日本語', 'ko-kr': '한국어',
}
GROUPS = {
    'language': 'Language selection', 'action': 'World interactions',
    'hud': 'HUD and feedback', 'weapon': 'Weapons', 'feedback': 'Common actions',
    'actors': 'NPC and monsters', 'items': 'Equipment names',
    'creation': 'Character Creation', 'settings': 'Player settings',
}
KEY_RE = re.compile(r'^[a-z][a-z0-9_]*\.[a-z][a-z0-9_]*$')


def read_catalog(root: Path) -> dict:
    path = Path(root) / 'assets/manifests/game-localization.json'
    data = json.loads(path.read_text(encoding='utf-8'))
    if set(data) != {'schemaVersion', 'defaultLocale', 'locales', 'groups'} or data['schemaVersion'] != 1:
        raise ValueError('game localization schema v1 required')
    if data['defaultLocale'] != 'en-us' or data['locales'] != NAMES:
        raise ValueError('game locale list or names mismatch')
    if set(data['groups']) != set(GROUPS):
        raise ValueError('game localization groups mismatch')
    if len({key for group in data['groups'].values() for key in group}) != sum(len(group) for group in data['groups'].values()):
        raise ValueError('duplicate localization key')
    source_values = set()
    for category, phrases in data['groups'].items():
        if not isinstance(phrases, dict) or not phrases:
            raise ValueError(f'{category}: empty group')
        for key, row in phrases.items():
            if not KEY_RE.fullmatch(key) or not key.startswith(category + '.'):
                raise ValueError(f'invalid localization key: {key}')
            if set(row) != {'source', 'translations'}:
                raise ValueError(f'{key}: wrong fields')
            if not isinstance(row['source'], str) or not row['source'].strip():
                raise ValueError(f'{key}: empty source')
            if row['source'] in source_values:
                # Exact source->key lookup must remain deterministic across all consumers.
                raise ValueError(f'{key}: duplicate source text {row["source"]!r}')
            source_values.add(row['source'])
            if set(row['translations']) != set(LOCALES):
                raise ValueError(f'{key}: missing or unknown locale')
            placeholders = set(re.findall(r'{([a-z_][a-z0-9_]*)}', row['source']))
            for locale, value in row['translations'].items():
                if not isinstance(value, str) or not value.strip() or len(value) > 700:
                    raise ValueError(f'{key}/{locale}: translation must be nonempty text')
                if set(re.findall(r'{([a-z_][a-z0-9_]*)}', value)) != placeholders:
                    raise ValueError(f'{key}/{locale}: placeholders differ from source')
    return data


def as_luau(value, level=0):
    if isinstance(value, dict):
        if not value:
            return '{}'
        chunks = []
        for key, item in value.items():
            chunks.append(' ' * (level + 4) + '[' + json.dumps(key, ensure_ascii=False) + '] = ' + as_luau(item, level + 4) + ',')
        return '{\n' + '\n'.join(chunks) + '\n' + ' ' * level + '}'
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, int):
        return str(value)
    raise ValueError('unsupported export value')


def emit_luau(root: Path) -> str:
    data = read_catalog(root)
    result = ('-- GENERATED by system/control-center/localization/catalog.py; DO NOT EDIT.\n'
              '-- Game UI only. Studio/Control Center is not translated.\n'
              'return table.freeze(' + as_luau(data) + ')\n')
    return result


def main():
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[3]
    output = root / 'src/shared/localization/GameTextCatalog.luau'
    result = emit_luau(root)
    if args.check:
        if not output.exists() or output.read_text(encoding='utf-8') != result:
            raise SystemExit('Game localization Runtime catalog is stale; regenerate it')
        print('Game localization: all languages complete; Luau export current')
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(result, encoding='utf-8', newline='\n')
        print('Game localization Runtime catalog regenerated')


if __name__ == '__main__':
    main()
