"""Compile exact Roblox Studio oracle captures into a server-only registry.

No FBX-space approximations, network access or automatic publication. The next
migration stage supplies verified captures from the canonical assembly path.
"""
from __future__ import annotations

import argparse
import json
import math
import os
from pathlib import Path
import tempfile
from threading import RLock

_WRITE_LOCK = RLock()
VERSION = 2
MAX_ROWS = 4096
MAX_BYTES = 32 * 1024 * 1024
ROOT = Path(__file__).resolve().parents[3]
REGISTRY = ROOT / 'src/server/combat/HitboxAssetRegistry.luau'
HEADER = '-- Generated by system/control-center/services/hitbox_asset_registry.py.\n-- Server-only. Do not hand-edit.\n'
EMPTY = '-- Empty until real Studio oracle captures have been imported. Server-only.\nreturn {schemaVersion = 2, entries = {}}\n'


def number(value, *, positive=False, integer=False):
    if type(value) not in (int, float) or not math.isfinite(value) or (positive and value <= 0) or (integer and value % 1):
        raise ValueError('invalid numeric hitbox field')
    return value


def sequence(value):
    if value == {}:  # HttpService may encode an empty table as an object.
        return []
    if not isinstance(value, list):
        raise ValueError('expected hitbox array')
    return value


def string(value):
    if not isinstance(value, str) or not value:
        raise ValueError('expected nonempty hitbox string')
    return value


def vector(value, positive=False):
    if not isinstance(value, list) or len(value) != 3:
        raise ValueError('expected three-vector')
    return [number(x, positive=positive) for x in value]


def box(value, *, head=False, record_count):
    if not isinstance(value, dict):
        raise ValueError('invalid hitbox')
    kind = value.get('kind')
    if kind not in (('head',) if head else ('mesh', 'bone')):
        raise ValueError('invalid hitbox anchor kind')
    result = {'kind': kind, 'center': vector(value.get('center')), 'size': vector(value.get('size'), True)}
    if not head:
        index = number(value.get('recordIndex'), positive=True, integer=True)
        if index > record_count:
            raise ValueError('hitbox anchor index exceeds signature records')
        result['recordIndex'] = index
    if kind in ('head', 'bone'):
        result['boneName'] = string(value.get('boneName'))
    return result


def normalize(payload):
    if not isinstance(payload, dict) or type(payload.get('schemaVersion')) is not int or payload['schemaVersion'] != VERSION:
        raise ValueError('unsupported hitbox schema')
    rows = sequence(payload.get('entries'))
    if len(rows) > MAX_ROWS:
        raise ValueError('too many hitbox entries')
    entries = {}
    for row in rows:
        if not isinstance(row, dict):
            raise ValueError('invalid hitbox entry')
        key, signature = string(row.get('key')), string(row.get('signature'))
        sig = json.loads(signature)
        if not isinstance(sig, list) or len(sig) != 6 or not isinstance(sig[0], list) or not sig[0]:
            raise ValueError('invalid assembly signature')
        for part in sig[0]:
            if not isinstance(part, list) or len(part) != 5 or not isinstance(part[1], str) or not part[1].startswith('rbxassetid://') or not part[1][13:].isdigit():
                raise ValueError('signature requires published mesh IDs')
        definition = row.get('definition')
        if not isinstance(definition, dict):
            raise ValueError('invalid definition')
        body = [box(v, record_count=len(sig[0])) for v in sequence(definition.get('bodyBoxes'))]
        d = {'broadRadius': number(definition.get('broadRadius'), positive=True),
             'sourceVertexCount': number(definition.get('sourceVertexCount'), positive=True, integer=True),
             'bodyBoxes': body}
        if definition.get('headBox') is not None:
            d['headBox'] = box(definition['headBox'], head=True, record_count=len(sig[0]))
        if not body and 'headBox' not in d:
            raise ValueError('definition contains no boxes')
        identity = (key, signature)
        if identity in entries:
            raise ValueError('duplicate hitbox entry')
        item = {'key': key, 'signature': signature, 'definition': d}
        if key.startswith('component|'):
            component = row.get('component')
            if len(sig[0]) != 1 or not isinstance(component, dict):
                raise ValueError('invalid character component signature')
            dependencies = [string(v) for v in sequence(component.get('dependencies'))]
            if dependencies != sorted(set(dependencies)) or any(b.get('boneName') not in dependencies for b in body if b['kind'] == 'bone'):
                raise ValueError('invalid component dependencies')
            item['component'] = {'dependencies': dependencies}
            raw = component.get('rawHead')
            if ('headBox' in d) != (raw is not None):
                raise ValueError('missing or unexpected component raw head bounds')
            if raw is not None:
                low, high = vector(raw.get('minimum')), vector(raw.get('maximum'))
                if any(a > b for a, b in zip(low, high)):
                    raise ValueError('reversed raw head bounds')
                # Same oracle padding and minimum axis; reject unrelated head data.
                for a, b, center, size in zip(low, high, d['headBox']['center'], d['headBox']['size']):
                    if abs((a+b)/2-center) > 1e-5 or abs(max(.05,b-a+.03)-size) > 1e-5:
                        raise ValueError('component head bounds mismatch')
                item['component']['rawHead'] = {'minimum': low, 'maximum': high}
        elif row.get('component') is not None:
            raise ValueError('unexpected component metadata')
        entries[identity] = item
    return {'schemaVersion': VERSION, 'entries': [entries[k] for k in sorted(entries)]}


def render(payload):
    data = json.dumps(normalize(payload), ensure_ascii=False, allow_nan=False, separators=(',', ':'))
    if len(data.encode('utf-8')) > MAX_BYTES:
        raise ValueError('registry exceeds size limit')
    # Long brackets with a collision-free delimiter; captured strings can
    # never become executable Lua. JSONDecode is the sole data decoder.
    equals = '='
    while ']' + equals + ']' in data:
        equals += '='
    return HEADER + 'return game:GetService("HttpService"):JSONDecode([' + equals + '[' + data + ']' + equals + '])\n'


def read_registry(path):
    text = path.read_text(encoding='utf-8')
    if text == '-- Generated by system/control-center/services/hitbox_asset_registry.py.\n' + EMPTY:
        return {'schemaVersion': VERSION, 'entries': []}
    prefix = HEADER + 'return game:GetService("HttpService"):JSONDecode(['
    if not text.startswith(prefix):
        raise ValueError('unrecognized generated registry; refusing overwrite')
    tail = text[len(prefix):]
    equals, data = tail.split('[', 1)
    suffix = ']' + equals + '])\n'
    if not equals or set(equals) != {'='} or not data.endswith(suffix):
        raise ValueError('invalid generated registry')
    return normalize(json.loads(data[:-len(suffix)]))


def merge(existing, incoming):
    entries = {(r['key'], r['signature']): r for r in normalize(existing)['entries']}
    for row in normalize(incoming)['entries']:
        key = (row['key'], row['signature'])
        if key in entries and entries[key] != row:
            raise ValueError('conflicting oracle captures; review before replacing')
        entries[key] = row
    return normalize({'schemaVersion': VERSION, 'entries': list(entries.values())})


def import_capture(source, destination=REGISTRY):
    if source.stat().st_size > MAX_BYTES:
        raise ValueError('capture exceeds size limit')
    return import_payload(json.loads(source.read_text(encoding='utf-8-sig')), destination)


def import_payload(payload, destination=REGISTRY):
    with _WRITE_LOCK:
        return _import_payload(payload, destination)


def _import_payload(payload, destination):
    payload = normalize(payload)
    if not payload['entries']:
        raise ValueError('empty capture; no asset definitions to import')
    result = merge(read_registry(destination), payload)
    return _write(result, destination)


def replace_character_components(slug, payload, destination=REGISTRY):
    marker = "|identity:" + slug + "|head:"
    def belongs(row):
        return row["key"].startswith("component|") and marker in row["key"]
    with _WRITE_LOCK:
        incoming = normalize(payload)
        if not incoming["entries"] or not all(belongs(row) for row in incoming["entries"]):
            raise ValueError("invalid scoped component capture")
        existing = read_registry(destination)
        existing["entries"] = [row for row in existing["entries"] if not belongs(row)]
        return _write(merge(existing, incoming), destination)


def _write(result, destination):
    text = render(result)
    with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', newline='\n', dir=destination.parent, delete=False) as handle:
        tmp = Path(handle.name)
        handle.write(text)
    try:
        os.replace(tmp, destination)
    finally:
        tmp.unlink(missing_ok=True)
    return len(result['entries'])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('capture', type=Path)
    args = parser.parse_args()
    print(f'Hitbox registry: {import_capture(args.capture)} verified-format entries (native parity still required)')
