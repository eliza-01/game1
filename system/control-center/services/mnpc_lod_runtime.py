"""Project current, verified MNPC LOD assets into the shared runtime registry.
No Model ID is used as a Mesh ID. Missing/stale rows retain their distance policy.
"""
from pathlib import Path
import math
from .game_balance import _lua, atomic

DEFAULT = {'enabled': True, 'full': 100, 'hide': 200, 'hysteresis': 10}


def _vector(value, length):
    return isinstance(value, list) and len(value) == length and all(
        type(x) in (int, float) and math.isfinite(x) for x in value)


def _id(value):
    return isinstance(value, str) and value.isascii() and value.isdecimal() and int(value) > 0


def asset(row):
    a = row.get('alignment') or {}
    if row.get('status') != 'PUBLISHED' or row.get('alignmentStatus') != 'GEOMETRY_VERIFIED':
        return None
    from .mnpc_lod_alignment import identity
    if a.get('identity') != identity(row) or not _id(a.get('meshId')) or not _id(row.get('imageAssetId')):
        return None
    size, frame = a.get('size'), a.get('rootCFrame')
    if not _vector(size, 3) or not _vector(frame, 12) or not all(.001 <= x <= 2048 for x in size):
        return None
    # Alignment admits only proper signed permutations. Recheck before export.
    r = frame[3:]
    if (any(x not in (-1, 0, 1) for x in r) or
        any(sum(abs(r[i*3+j]) for j in range(3)) != 1 for i in range(3)) or
        any(sum(abs(r[i*3+j]) for i in range(3)) != 1 for j in range(3)) or
        r[0]*(r[4]*r[8]-r[5]*r[7])-r[1]*(r[3]*r[8]-r[5]*r[6])+r[2]*(r[3]*r[7]-r[4]*r[6]) != 1):
        return None
    return {'meshId': a['meshId'], 'imageId': row['imageAssetId'], 'size': size, 'rootCFrame': frame,
            'revision': row['revision'], 'fullModelId': row['fullModelId']}


def projection(overview):
    data = {'schemaVersion': 1, 'defaults': overview['settings']['defaults'], 'actors': {}}
    for row in overview['items']:
        entry = {'profile': row['profile']}
        ready = asset(row)
        if ready:
            entry['asset'] = ready
        data['actors'][row['kind'] + ':' + row['slug']] = entry
    return data


def export(owner):
    with owner._lock:
        content = '-- Generated by MNPC Runtime export. Missing entries deliberately use the red stub.\nreturn ' + _lua(projection(owner.overview())) + '\n'
        path = Path(owner.root) / 'src/shared/world/MnpcLodRegistry.luau'
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text(encoding='utf-8') != content:
            atomic(path, content)
    return path


def affects_runtime(path):
    return path.startswith(('/api/lod-manager/mnpc/', '/api/monsters', '/api/npcs',
                            '/api/npc-', '/api/monster-', '/api/weapons', '/api/weapon-',
                            '/api/texture-atlases', '/api/asset-retirement', '/api/animations'))
